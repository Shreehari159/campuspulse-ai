// Persistence functions ensuring data survives server restarts
export function getDatabase(): DatabaseState {
  try {
    if (!fs.existsSync(DATA_DIR)) {
      fs.mkdirSync(DATA_DIR, { recursive: true });
    }
    if (fs.existsSync(DB_FILE)) {
      const content = fs.readFileSync(DB_FILE, 'utf-8');
      const parsed = JSON.parse(content);
      // Ensure all required top-level collections exist
      return {
        ...initialDatabase,
        ...parsed,
        subscriptionPlans: parsed.subscriptionPlans || initialDatabase.subscriptionPlans,
        tenantSubscriptions: parsed.tenantSubscriptions || initialDatabase.tenantSubscriptions,
        aiModels: parsed.aiModels || initialDatabase.aiModels,
        auditEvents: parsed.auditEvents || initialDatabase.auditEvents,
      };
    }
  } catch (err) {
    console.error('Error loading database from disk, using fallback initial data:', err);
  }
  return JSON.parse(JSON.stringify(initialDatabase));
}

export function saveDatabase(data: DatabaseState): void {
  try {
    if (!fs.existsSync(DATA_DIR)) {
      fs.mkdirSync(DATA_DIR, { recursive: true });
    }
    fs.writeFileSync(DB_FILE, JSON.stringify(data, null, 2), 'utf-8');
  } catch (err) {
    console.error('Error writing database to disk:', err);
  }
}
